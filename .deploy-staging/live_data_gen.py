CATEGORY_LABEL = {
    "退款": "退款",
    "换货": "换货",
    "物流": "物流",
    "发票": "发票",
    "优惠券": "优惠券",
    "商品咨询": "商品咨询",
    "投诉": "投诉",
    "账号问题": "账号问题",
}


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "intent_classify.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["order_id", "question", "label"])
        for oid, q, label, _reply in TICKETS:
            w.writerow([oid, q, CATEGORY_LABEL[label]])
    with open(os.path.join(OUT_DIR, "service_reply.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["order_id", "question", "answer"])
        for oid, q, _label, reply in TICKETS:
            w.writerow([oid, q, reply])
    counts = {}
    for _oid, _q, label, _r in TICKETS:
        counts[label] = counts.get(label, 0) + 1
    print("rows:", len(TICKETS))
    print("by label:", counts)
    print("output:", OUT_DIR)


if __name__ == "__main__":
    main()
